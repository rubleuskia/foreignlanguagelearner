"""Pure file pipeline for whole books; no HTTP endpoint and no duration admission cap."""
import contextlib
import json
import math
from pathlib import Path, PurePosixPath
import shutil
import stat
import subprocess
from types import SimpleNamespace
import zipfile

import align
import epub_text
import word_timings
from backend.book_alignment.contract import (ARCHIVE_LIMIT, AUDIO_EXTENSIONS, ENTRY_LIMIT,
                                              EXPANDED_LIMIT, TEXT_LIMIT)


def unpack(source, destination):
    if not 0 < source.stat().st_size <= ARCHIVE_LIMIT:
        raise ValueError('INPUT_TOO_LARGE')
    with zipfile.ZipFile(source) as archive:
        entries = archive.infolist()
        if len(entries) > ENTRY_LIMIT or sum(item.file_size for item in entries) > EXPANDED_LIMIT:
            raise ValueError('INVALID_ARCHIVE')
        seen = set()
        for item in entries:
            path = PurePosixPath(item.filename)
            mode = item.external_attr >> 16
            if (not item.filename or path.is_absolute() or '..' in path.parts or '\\' in item.filename
                    or ':' in item.filename or '\x00' in item.filename or item.filename in seen
                    or stat.S_ISLNK(mode) or item.flag_bits & 1):
                raise ValueError('INVALID_ARCHIVE')
            seen.add(item.filename)
            target = destination.joinpath(*path.parts)
            if item.is_dir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.open(item) as incoming, target.open('xb') as output:
                    shutil.copyfileobj(incoming, output, 1024 * 1024)
    manifest = json.loads((destination / 'input.json').read_text(encoding='utf-8'))
    if set(manifest) != {'schemaVersion', 'audio', 'text'} or manifest['schemaVersion'] != 1:
        raise ValueError('INVALID_ARCHIVE')
    paths = manifest['audio']
    text = manifest['text']
    if (not isinstance(paths, list) or not 1 <= len(paths) <= 500 or not isinstance(text, str)
            or any(not isinstance(path, str) for path in paths) or len(set(paths)) != len(paths)):
        raise ValueError('INVALID_ARCHIVE')
    for path in paths + [text]:
        if path not in seen or not (destination / path).is_file():
            raise ValueError('INVALID_ARCHIVE')
    if any(Path(path).suffix.lower()[1:] not in AUDIO_EXTENSIONS for path in paths):
        raise ValueError('INVALID_AUDIO')
    if Path(text).suffix.lower() not in {'.txt', '.epub'}:
        raise ValueError('INVALID_TEXT')
    return [destination / path for path in paths], destination / text


def probe(audio):
    result = subprocess.run(['ffprobe', '-v', 'error', '-show_entries',
        'format=duration:stream=codec_type:stream_disposition=attached_pic', '-of', 'json', str(audio)],
        check=True, capture_output=True, text=True, timeout=60)
    info = json.loads(result.stdout)
    duration = float(info['format']['duration'])
    streams = info.get('streams', [])
    if (not math.isfinite(duration) or duration <= 0
            or not any(s.get('codec_type') == 'audio' for s in streams)
            or any(s.get('codec_type') == 'video' and s.get('disposition', {}).get('attached_pic') != 1 for s in streams)):
        raise ValueError('INVALID_AUDIO')
    return duration


def validate_cues(cues, duration):
    if not cues:
        raise ValueError('INVALID_TIMINGS')
    previous = 0
    for cue in cues:
        start, end = cue['start'], cue['end']
        if (any(isinstance(t, bool) or not isinstance(t, (int, float)) or not math.isfinite(t) for t in (start, end))
                or start < previous or end <= start or end > duration * 1000 + 100):
            raise ValueError('INVALID_TIMINGS')
        previous = end


def process(source, root, job, model_dir, stage, engine=align.run):
    inputs = root / 'inputs'
    inputs.mkdir()
    stage('preparing', 15)
    tracks, text = unpack(source, inputs)
    if text.stat().st_size > TEXT_LIMIT:
        raise ValueError('INVALID_TEXT')
    if text.suffix.lower() == '.epub':
        extracted = epub_text.extract(text)
        content = '\n\n'.join(section['text'] for section in extracted['sections'])
    else:
        content = text.read_text(encoding='utf-8-sig')
    content = align.clean_text(content)
    if not content or len(content.encode()) > TEXT_LIMIT:
        raise ValueError('INVALID_TEXT')
    transcript = root / 'transcript.txt'
    transcript.write_text(content, encoding='utf-8')
    # Normalize heterogeneous inputs before concatenation. Filenames here are generated by us.
    normalized = root / 'normalized'
    normalized.mkdir()
    for index, track in enumerate(tracks):
        probe(track)
        subprocess.run(['ffmpeg', '-nostdin', '-v', 'error', '-i', str(track), '-vn', '-ac', '1',
            '-ar', '16000', '-c:a', 'pcm_s16le', str(normalized / f'{index:04d}.wav')],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        stage('preparing', 15 + int(15 * (index + 1) / len(tracks)))
    listing = normalized / 'tracks.txt'
    listing.write_text(''.join(f"file '{index:04d}.wav'\n" for index in range(len(tracks))), encoding='utf-8')
    audio = root / 'audio.m4a'
    subprocess.run(['ffmpeg', '-nostdin', '-v', 'error', '-f', 'concat', '-safe', '1', '-i', str(listing),
        '-c:a', 'aac', '-b:a', '64k', '-movflags', '+faststart', str(audio)], check=True,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    duration = probe(audio)
    stage('aligning', 35)
    output = root / 'alignment'
    with (root / 'private.log').open('w') as log, contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
        engine(SimpleNamespace(text=transcript, audio=audio, alignment_json=None, output=output,
            language=job['language'], model='base', token_step=100, guided=True, allow_untimed_words=True,
            device='cpu', model_dir=Path(model_dir), format='both', max_chars=42,
            max_duration=6.0, max_gap=0.8, offset=0.0))
    stage('validating', 85)
    report = json.loads((output / 'alignment.json').read_text(encoding='utf-8'))
    validate_cues(report.get('cues'), duration)
    package = root / 'book'
    package.mkdir()
    shutil.move(audio, package / 'audio.m4a')
    shutil.copyfile(transcript, package / 'transcript.txt')
    shutil.copyfile(output / 'subtitles.srt', package / 'subtitles.srt')
    digest = word_timings.file_hash(package / 'audio.m4a')
    timing = word_timings.make_file(report, (package / 'subtitles.srt').read_text(), 'book', digest, duration)
    (package / 'words.json').write_bytes(timing)
    review = bool(report.get('requires_review'))
    manifest = {'format': 'foreign-language-learner.book', 'schemaVersion': 1, 'title': job['title'],
        'sourceLanguage': job['language'], 'transcript': 'transcript.txt',
        'tracks': [{'id': 'book', 'title': job['title'], 'audio': 'audio.m4a', 'subtitle': 'subtitles.srt',
                    'wordTimings': 'words.json', 'alignmentStatus': 'review-required' if review else 'aligned'}]}
    (package / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False), encoding='utf-8')
    result = root / 'book.book.zip'
    with zipfile.ZipFile(result, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(package.iterdir()):
            archive.write(path, path.name)
    return result, review
