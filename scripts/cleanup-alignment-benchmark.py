#!/usr/bin/env python3
"""Delete only the disposable benchmark stack bound to retained local evidence."""
import argparse
import json
from pathlib import Path

import boto3
from botocore.config import Config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stack', default='ForeignLanguageLearnerAudioBenchmark')
    parser.add_argument('--project', required=True)
    parser.add_argument('--profile', default='fll-control')
    parser.add_argument('--evidence', type=Path, required=True)
    args = parser.parse_args()
    report = json.loads((args.evidence / 'aws-measurements.json').read_text())
    session = boto3.Session(profile_name=args.profile, region_name='eu-north-1')
    options = Config(connect_timeout=5, read_timeout=30, retries={'total_max_attempts': 2})
    sts, cf, ecs, s3 = (session.client(name, config=options) for name in ('sts', 'cloudformation', 'ecs', 's3'))
    if sts.get_caller_identity()['Account'] != args.project or report.get('project') != args.project:
        raise ValueError('Wrong project')
    stack = cf.describe_stacks(StackName=args.stack)['Stacks'][0]
    out = {row['OutputKey']: row['OutputValue'] for row in stack['Outputs']}
    if ({'Key': 'Purpose', 'Value': 'fll-audio-benchmark'} not in stack.get('Tags', [])
            or stack['StackId'] != report.get('stackId') or out['Bucket'] != report.get('bucket')):
        raise ValueError('Stack is not the disposable benchmark associated with these local results')
    for state in ['RUNNING', 'PENDING']:
        for page in ecs.get_paginator('list_tasks').paginate(cluster=out['Cluster'], desiredStatus=state):
            if page.get('taskArns'): raise ValueError('Wait for benchmark tasks to stop before cleanup')
    # This bucket is uniquely generated by the checked stack and contains only disposable fixtures/results.
    for page in s3.get_paginator('list_object_versions').paginate(Bucket=out['Bucket']):
        rows = [{'Key': row['Key'], 'VersionId': row['VersionId']}
                for name in ['Versions', 'DeleteMarkers'] for row in page.get(name, [])]
        if rows:
            result = s3.delete_objects(Bucket=out['Bucket'], Delete={'Objects': rows, 'Quiet': True})
            if result.get('Errors'): raise RuntimeError('Could not clear temporary benchmark object versions')
    cf.delete_stack(StackName=stack['StackId'])
    print('Temporary benchmark stack deletion requested. Local evidence and the existing ECR repository are retained.')


if __name__ == '__main__':
    main()
